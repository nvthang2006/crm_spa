-- Every operational table is private to explicitly approved manager accounts.
do $$
declare table_name text;
begin
    foreach table_name in array array[
        'employees','work_schedules','service_categories','offerings','commission_rules','resource_areas','service_resources',
        'customers','customer_health_profiles','customer_packages','appointments','attendance_records','package_usages',
        'invoices','invoice_items','payments','invoice_refunds','commission_entries','payroll_periods','payroll_lines',
        'payroll_adjustments','operational_alerts','operational_alert_reads'
    ] loop
        execute format('alter table public.%I enable row level security', table_name);
        execute format('create policy manager_full_access on public.%I for all to authenticated using (private.has_manager_access()) with check (private.has_manager_access())', table_name);
    end loop;
end;
$$;
