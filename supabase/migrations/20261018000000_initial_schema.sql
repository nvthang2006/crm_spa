-- Fresh production schema for Sunny Beauty Desktop.
-- Monetary values remain VND integer units; all timestamps are timezone aware.

create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table public.app_access (
    user_id uuid primary key references auth.users(id) on delete cascade,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);
alter table public.app_access enable row level security;

create or replace function private.has_manager_access()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1 from public.app_access
        where user_id = (select auth.uid()) and is_active
    );
$$;
revoke all on function private.has_manager_access() from public, anon;
grant execute on function private.has_manager_access() to authenticated;

create or replace function public.has_app_access()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$ select private.has_manager_access(); $$;
revoke all on function public.has_app_access() from public, anon;
grant execute on function public.has_app_access() to authenticated;

create table public.employees (
    id bigint generated by default as identity primary key,
    code varchar(32) not null unique,
    name text not null,
    phone varchar(32), email text, job_title text not null, shift_name text,
