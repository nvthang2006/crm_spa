    p_business_name text,
    p_address text,
    p_phone text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    settings_before jsonb;
    settings_after jsonb;
begin
    if not coalesce(private.has_manager_access(), false) then
